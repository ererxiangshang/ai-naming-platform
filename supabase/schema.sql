-- 1. 起名历史表
create table if not exists name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result text not null,
  model_name text not null,
  created_at timestamp with time zone default now()
);

-- 2. 常用查询的索引
create index if not exists name_history_created_at_idx
  on name_history (created_at desc);

comment on table name_history is 'AI 起名平台的历史记录：需求、生成的方案、使用的模型';

-- ============================================================
-- 3. 权限（RLS）
--    实验 / 调试阶段：可以先执行下面的语句临时关闭 RLS，方便验证写入。
--    alter table name_history disable row level security;
--
--    正式上线推荐下面这套：服务端用 service_role key 写入，浏览器不直连数据库，
--    匿名用户只能读、不能写，避免历史被随意删改。
-- ============================================================
alter table name_history enable row level security;

-- 允许匿名（anon key）读取历史列表
drop policy if exists "public read name_history" on name_history;
create policy "public read name_history"
  on name_history
  for select
  to anon, authenticated
  using (true);

-- 写入交给服务端（service_role 会绕过 RLS），不开放给匿名用户
